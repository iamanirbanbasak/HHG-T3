def _web3(cfg: Config):
    """Public RPC is stateless; the in-process local chain must be reused in this process."""
    from .chain.deploy import make_web3

    if cfg.network != "local":
        return make_web3(cfg)
    w3 = _LOCAL.get("w3")
    if w3 is None:
        w3 = make_web3(cfg)
        _LOCAL["w3"] = w3
    return w3


def _contract_address(cfg: Config, payload: dict | None = None) -> str:
    raw = ""
    if payload:
        raw = str(payload.get("contract") or "").strip()
    if not raw and cfg.network == "local":
        raw = str(_LOCAL.get("contract") or "")
    if not raw:
        raw = str(cfg.contract_address or "")
    if not raw:
        cfg.require("contract_address")
    return raw


def _artifact_media_type(name: str) -> str | None:
    if name in ARTIFACT_FILES:
        return ARTIFACT_FILES[name]
    if _CANDIDATE_THUMB.fullmatch(name):
        return "image/jpeg"
    return None


def _artifact_inventory(run_dir: Path) -> dict[str, Any]:
    images = [
        n for n in ("probe.jpg", "probe_head.png", "probe_aligned.png", "candidate.jpg")
        if (run_dir / n).is_file()
    ]
    thumbs: list[str] = []
    cdir = run_dir / "candidates"
    if cdir.is_dir():
        for p in sorted(cdir.glob("c*.jpg")):
            rel = f"candidates/{p.name}"
            if _CANDIDATE_THUMB.fullmatch(rel):
                thumbs.append(rel)
    return {"images": images, "candidate_thumbs": thumbs}


def _ensure_backup(run_dir: Path) -> None:
    from .evidence import EVIDENCE_JSON, POST_TEXT

    src = run_dir / POST_TEXT
    bak = run_dir / POST_TEXT_BACKUP
    if src.is_file() and not bak.is_file():
        shutil.copy2(src, bak)
    ev = run_dir / EVIDENCE_JSON
    ev_bak = run_dir / EVIDENCE_BACKUP
    if ev.is_file() and not ev_bak.is_file():
        shutil.copy2(ev, ev_bak)


def _strip_file_digests(bundle: dict[str, Any]) -> dict[str, Any]:
    """File-backed hashes are recomputed on every verify; they are not operator-editable."""
    out = json.loads(json.dumps(bundle))
    probe = out.get("probe")
    if isinstance(probe, dict):
        probe.pop("image_sha256", None)
    match = out.get("match")
    if isinstance(match, dict):
        match.pop("image_sha256", None)
        match.pop("post_text_sha256", None)
    return out


def _apply_evidence_edit(run_dir: Path, stored: dict[str, Any]) -> dict[str, Any]:
    """Write operator JSON, then persist the rebuilt bundle (file hashes filled in)."""
    from .evidence import EVIDENCE_JSON, canonicalise, evidence_hash, rebuild_from_artifacts, write_bundle

    _ensure_backup(run_dir)
    prev: dict[str, Any] = {}
    path = run_dir / EVIDENCE_JSON
    if path.is_file():
        prev = json.loads(path.read_text(encoding="utf-8"))
    write_bundle(run_dir, stored)
    rebuilt = rebuild_from_artifacts(run_dir)
    write_bundle(run_dir, rebuilt)
    metadata_unchanged = canonicalise(_strip_file_digests(stored)) == canonicalise(
        _strip_file_digests(prev)
    )
    ignored = False
    s_probe, r_probe = stored.get("probe") or {}, rebuilt.get("probe") or {}
    s_match, r_match = stored.get("match") or {}, rebuilt.get("match") or {}
    for key, src, dst in (
        ("image_sha256", s_probe, r_probe),
        ("image_sha256", s_match, r_match),
        ("post_text_sha256", s_match, r_match),
    ):
        if key in src and src.get(key) != dst.get(key):
            ignored = True
            break
    return {
        "evidence": rebuilt,
        "evidence_hash": "0x" + evidence_hash(rebuilt).hex(),
        "digest_only_edit": metadata_unchanged and ignored,
    }


def _apply_pending_edits(run_dir: Path, payload: dict) -> dict[str, Any]:
    """Persist whatever is in the browser editor before hashing / verifying."""
    from .evidence import POST_TEXT, evidence_hash, rebuild_from_artifacts

    notes: dict[str, Any] = {}
    if payload.get("post_text") is not None:
        text = str(payload.get("post_text") or "")
        if len(text.encode("utf-8")) > POST_TEXT_CAP:
            raise FaceChainError("post text exceeds size cap")
        _ensure_backup(run_dir)
        (run_dir / POST_TEXT).write_text(text, encoding="utf-8")
    if payload.get("evidence_text"):
        notes = _apply_evidence_edit(run_dir, _parse_evidence_text(str(payload["evidence_text"])))
    rebuilt = rebuild_from_artifacts(run_dir)
    notes.setdefault("evidence", rebuilt)
    notes.setdefault("evidence_hash", "0x" + evidence_hash(rebuilt).hex())
    return notes


def _parse_evidence_text(text: str) -> dict[str, Any]:
    """Accept operator-edited JSON. Must still be a bundle rebuild can read."""
    raw = text.encode("utf-8")
    if len(raw) > EVIDENCE_CAP:
        raise FaceChainError("evidence.json exceeds size cap")
    try:
        stored = json.loads(text)
    except json.JSONDecodeError as exc:
        raise FaceChainError(f"evidence.json is not valid JSON: {exc.msg}") from exc
    if not isinstance(stored, dict):
        raise FaceChainError("evidence.json must be an object")
    for section in ("schema", "probe", "search", "match", "verification"):
        if section not in stored:
            raise FaceChainError("evidence bundle malformed", {"missing_key": section})
    return stored


def _tx_0x(raw: str) -> str:
    h = str(raw or "").strip()
    if h.startswith("0x") or h.startswith("0X"):
        return "0x" + h[2:].lower()
    return "0x" + h.lower() if h else ""


def _result_from_run_dir(run_dir: Path, cfg: Config) -> dict[str, Any]:
    """Rebuild the UI payload from files on disk so a saved run can be opened without re-scanning."""
    from .config import CHAIN_IDS
    from .evidence import (
        EVIDENCE_JSON,
        POST_TEXT,
        RECEIPT_JSON,
        evidence_hash,
        rebuild_from_artifacts,
        similarity_bps,
    )

    _ensure_backup(run_dir)
    stored = json.loads((run_dir / EVIDENCE_JSON).read_text(encoding="utf-8"))
    post_path = run_dir / POST_TEXT
    post_text = post_path.read_text(encoding="utf-8", errors="replace") if post_path.is_file() else ""
    bak = run_dir / POST_TEXT_BACKUP
    original = bak.read_text(encoding="utf-8", errors="replace") if bak.is_file() else post_text
    h = evidence_hash(rebuild_from_artifacts(run_dir))
    receipt = None
    rec_path = run_dir / RECEIPT_JSON
    if rec_path.is_file():
        receipt = json.loads(rec_path.read_text(encoding="utf-8"))

    match = stored.get("match") or {}
    ver = stored.get("verification") or {}
    search = stored.get("search") or {}
    net = (receipt or {}).get("network") or cfg.network
    contract = (receipt or {}).get("contract_address") or cfg.contract_address
    cosine = float(ver.get("cosine_similarity") or 0)
    anchored = None
    if receipt and receipt.get("evidence_hash"):
        anchored = receipt["evidence_hash"]
        if not str(anchored).startswith("0x"):
            anchored = "0x" + anchored
    return {
        "match": match.get("post_url"),
        "cosine": round(cosine, 4),
        "threshold": ver.get("threshold", cfg.threshold),
        "candidates": search.get("n_candidates"),
        "social": search.get("n_social"),
        "verified": search.get("n_face_verified"),
        "rows": [],
        "accounts": [],
        "resolved_handle": match.get("author_handle"),
        "resolved_profile": None,
        "linked": [],
        "evidence_hash": "0x" + h.hex(),
        "evidence": stored,
        "post_text": post_text,
        "original_post_text": original,
        "similarity_bps": similarity_bps(cosine),
        "record_id": None if receipt is None else receipt.get("record_id"),
        "tx": _tx_0x((receipt or {}).get("tx_hash") or ""),
        "awaiting_anchor": receipt is None,
        "network": net,
        "chain_id": CHAIN_IDS.get(net),
        "provider": search.get("provider"),
        "attempts": [],
        "contract": contract,
        "run_dir": _rel_to_project(run_dir),
        "verified_match": None,
        "anchored_hash": anchored,
        "loaded": True,
        **_artifact_inventory(run_dir),
    }


def _account_json(a) -> dict[str, Any]:
    payload = {
        "display": a.display,
        "platform": a.platform,
        "handle": a.handle,
        "profile_url": a.profile_url,
        "urls": list(a.urls),
        "origin": a.origin,
        "cosine": None if a.origin == "linked" else round(a.best_cosine, 4),
    }
    return payload


def _cfg(payload: dict) -> Config:
    from .cli import _load_dotenv

    _load_dotenv()
    return load_config(
        # Fall through to NETWORK in .env rather than forcing "local". Hardcoding the fallback
        # meant a configured testnet was silently ignored and runs anchored to a throwaway
        # in-process chain while the UI displayed the real contract address.
        network=payload.get("network") or None,
        threshold=payload.get("threshold"),
        search_provider=payload.get("provider") or None,
    )


def _run_job(job: Job, payload: dict) -> None:
    """Drive the same code path as `facechain run`."""
    from .evidence import evidence_hash, similarity_bps
    from .pipeline import run as run_pipeline

    try:
        cfg = _cfg(payload)
        image = safe_image_path(payload["image"]) if payload.get("image") else None

        if payload.get("capture"):
            from .capture import capture_face

            job.log("opening camera...", "step")
            image, score, attempts = capture_face(Path("capture.jpg"))
            job.log(f"captured {image.name}  det_score={score:.4f}  ({attempts} attempt)", "ok")

        if image is None:
            raise FaceChainError("no input image")

        from .providers import resolve_chain

        chain = " -> ".join(n for n, _ in resolve_chain(cfg))
        job.log(f"providers: {chain}   network={cfg.network}  tau={cfg.threshold}", "dim")
        job.log("detecting face and computing embedding...", "step")

        result = run_pipeline(image, cfg)
        job.log(
            f"lens returned {result.n_candidates} candidates, "
            f"{result.n_social} on social domains", "info"
        )
        job.log(f"independently embedded and scored {len(result.scored)} candidates", "step")

        rows = [
            {
                "url": s.candidate.page_url,
                "cosine": round(s.cosine, 4),
                "pass": s.cosine >= cfg.threshold,
            }
            for s in result.scored[:12]
        ]
        for s in result.expanded:
            rows.append({
                "url": s.candidate.page_url,
                "cosine": round(s.cosine, 4),
                "pass": True,
            })
        for r in rows:
            job.log(
                f"  {r['cosine']:.4f}  {'PASS  ' if r['pass'] else 'reject'}  {r['url'][:64]}",
                "ok" if r["pass"] else "dim",
            )

        from .profiles import group_accounts

        survivors = []
        for s in result.scored:
            if s.cosine < cfg.threshold:
                continue
            url = s.candidate.page_url
            if (
                result.resolved_profile
                and s.candidate.page_url == result.top.candidate.page_url
            ):
                url = result.resolved_profile
            survivors.append((url, s.cosine))
        survivors.extend((s.candidate.page_url, s.cosine) for s in result.expanded)
        accounts = group_accounts(survivors)
        linked = result.linked
        by_key = {(a.platform, a.handle): a for a in accounts}
        for extra in linked:
            key = (extra.platform, extra.handle)
            existing = by_key.get(key)
            if existing is None:
                accounts.append(extra)
                by_key[key] = extra
                continue
            for u in extra.urls:
                if u not in existing.urls:
                    existing.urls.append(u)
            if extra.profile_url and extra.profile_url not in existing.urls:
                existing.urls.append(extra.profile_url)
        if result.resolved_handle:
            job.log(f"account  @{result.resolved_handle}  {result.resolved_profile}", "ok")
            post = result.top.candidate.page_url
            for a in accounts:
                if a.handle == result.resolved_handle and post not in a.urls:
                    a.urls.append(post)

        for a in result.attempts:
            job.log(f"  {a['provider']}: {a['outcome'].replace('_', ' ')}"
                    + (f" (best {a['best']})" if "best" in a else ""), "dim")
        job.log(f"matched via {result.provider}", "ok")
        job.log(f"{len(survivors)} match(es) above threshold, "
                f"across {len(accounts)} account(s)", "ok")
        for a in accounts:
            job.log(f"  {a.display}  best cosine {a.best_cosine:.4f}", "ok")
            for u in a.urls:
                job.log(f"      {u}", "dim")

        if result.expanded:
            job.log(
                f"{len(result.expanded)} further account(s) from the verified handle "
                f"(each independently face-scored)",
                "info",
            )
            for s in result.expanded:
                job.log(
                    f"  {s.cosine:.4f}  PASS   {s.candidate.page_url[:64]}",
                    "ok",
                )

        if linked:
            job.log(
                f"{len(linked)} profile(s) linked from the verified page "
                f"(not independently face-scored)",
                "info",
            )
            for a in linked:
                job.log(f"  {a.display}", "ok")
                for u in a.urls:
                    job.log(f"      {u}", "dim")

        from .config import CHAIN_IDS
        from .evidence import POST_TEXT as POST_TEXT_FILE

        h = evidence_hash(result.bundle)
        post_text = (result.run_dir / POST_TEXT_FILE).read_text(encoding="utf-8", errors="replace")
        _ensure_backup(result.run_dir)
        rel_run = _rel_to_project(result.run_dir)
        job.log(
            "face match sealed locally. review the artifacts, then sign the on-chain tx.",
            "ok",
        )

        job.result = {
            "match": result.top.candidate.page_url,
            "cosine": round(result.top.cosine, 4),
            "threshold": cfg.threshold,
            "candidates": result.n_candidates,
            "social": result.n_social,
            "verified": result.n_verified,
            "rows": rows,
            "accounts": [_account_json(a) for a in accounts],
            "resolved_handle": result.resolved_handle,
            "resolved_profile": result.resolved_profile,
            "linked": [_account_json(a) for a in linked],
            "evidence_hash": "0x" + h.hex(),
            "evidence": result.bundle,
            "post_text": post_text,
            "original_post_text": post_text,
            "similarity_bps": similarity_bps(result.top.cosine),
            "record_id": None,
            "tx": None,
            "awaiting_anchor": True,
            "network": cfg.network,
            "chain_id": CHAIN_IDS.get(cfg.network),
            "provider": result.provider,
            "attempts": result.attempts,
            "contract": cfg.contract_address,
            "run_dir": rel_run,
            "verified_match": None,
            "loaded": False,
            **_artifact_inventory(result.run_dir),
        }
        job.ok = True

    except NoFaceDetectedError as exc:
        job.log(f"NoFaceDetectedError: {exc}", "err")
    except SearchProviderError as exc:
        job.log(f"SearchProviderError: {exc}", "err")
        job.log("a provider failure is not the same as 'no results found'", "dim")
    except NoVerifiedMatchError as exc:
        # `attempts` is structured data; printing the exception repr floods the UI with a dict.
        job.log("no candidate cleared the threshold in any provider", "warn")
        for a in exc.context.get("attempts") or []:
            if a.get("outcome") == "provider_error":
                job.log(f"  {a['provider']:<12} unavailable - {str(a.get('detail',''))[:64]}", "dim")
            else:
                job.log(
                    f"  {a['provider']:<12} {a.get('candidates',0):>4} candidates -> "
                    f"{a.get('social',0):>3} profiles -> {a.get('scored',0):>3} face-scored -> "
                    f"best {a.get('best',0):.4f}", "dim")
        job.log(f"threshold {exc.context.get('threshold')}; nothing was anchored.", "warn")
        job.log("this is the honest negative path, not an error.", "dim")
    except ChainError as exc:
        job.log(f"ChainError: {exc}", "err")
    except FaceChainError as exc:
        # Any other domain error is expected and reported plainly, without a traceback.
        job.log(f"{type(exc).__name__}: {exc}", "err")
    except Exception as exc:  # noqa: BLE001
        job.log(f"unexpected: {type(exc).__name__}: {exc}", "err")
        job.log(traceback.format_exc()[-400:], "dim")
    finally:
        job.done = True


