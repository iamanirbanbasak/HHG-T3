    @app.post("/api/anchor/confirm")
    async def confirm_anchor(request: Request, payload: dict, x_csrf_token: str = Header(default="")):
        """Wait for a wallet-submitted tx and record the receipt."""
        _check_origin(request)
        if not secrets.compare_digest(x_csrf_token, CSRF_TOKEN):
            raise HTTPException(status_code=403, detail="missing or invalid CSRF token")
        from .chain.compile import compile_registry
        from .chain.deploy import make_web3
        from .chain.registry import Registry

        try:
            cfg = _cfg(payload)
            run_dir = safe_run_dir(str(payload.get("run_dir") or ""))
            cfg.require("contract_address")
            raw = str(payload.get("tx_hash") or "").strip()
            if raw.startswith("0x"):
                raw = raw[2:]
            tx_bytes = bytes.fromhex(raw)
            w3 = make_web3(cfg)
            receipt = w3.eth.wait_for_transaction_receipt(tx_bytes, timeout=300)
            if int(receipt["status"]) != 1:
                raise FaceChainError("anchor transaction reverted")
            abi, _ = compile_registry()
            reg = Registry(w3, cfg.contract_address, list(abi))
            logs = reg._c.events.MatchAnchored().process_receipt(receipt)
            if not logs:
                raise FaceChainError("anchor emitted no MatchAnchored event")
            rid = int(logs[0]["args"]["id"])
            tx = "0x" + raw.lower()
            h = _current_hash(run_dir)
            _write_receipt(
                run_dir, record_id=rid, tx=tx, network=cfg.network,
                contract=reg.address, evidence_hash_hex=h.hex(),
            )
        except FaceChainError as exc:
            raise HTTPException(status_code=400, detail=str(exc)) from exc
        except ValueError as exc:
            raise HTTPException(status_code=400, detail="tx_hash must be hex") from exc
        return {
            "record_id": rid,
            "tx": tx,
            "contract": reg.address,
            "evidence_hash": "0x" + h.hex(),
            "network": cfg.network,
        }

